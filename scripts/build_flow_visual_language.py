#!/usr/bin/env python3
"""从可移植视觉语言 JSON 生成 Web 与报告主题映射。"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "packages/flow-visual-language/tokens.json"
OUTPUTS = {
    ROOT / "packages/flow-visual-language/tokens.css": "css",
    ROOT / "apps/web/lib/visual-tokens.generated.ts": "ts",
    ROOT / "services/api/src/flow_api/visual_tokens.py": "py",
}


def flatten(value: dict, prefix: str = "") -> dict[str, str]:
    out = {}
    for key, item in value.items():
        name = f"{prefix}-{key}" if prefix else key
        if isinstance(item, dict):
            out.update(flatten(item, name))
        elif isinstance(item, list):
            for index, child in enumerate(item, 1):
                out[f"{name}-{index}"] = str(child)
        else:
            out[name] = str(item)
    return out


def css_name(value: str) -> str:
    return re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", value).lower()


def python_rows(values: dict[str, str]) -> list[str]:
    rows: list[str] = []
    for key, value in values.items():
        prefix = f"    {key!r}: "
        literal = repr(value)
        if len(prefix) + len(literal) + 1 <= 100:
            rows.append(f"{prefix}{literal},")
            continue

        chunks: list[str] = []
        current = ""
        for part in re.findall(r"\S+\s*", value):
            candidate = current + part
            if current and len(repr(candidate)) > 88:
                chunks.append(current)
                current = part
            else:
                current = candidate
        if current:
            chunks.append(current)
        rows.append(f"{prefix}(")
        rows.extend(f"        {chunk!r}" for chunk in chunks)
        rows.append("    ),")
    return rows


def generate(data: dict, kind: str) -> str:
    values = flatten({key: value for key, value in data.items() if key not in {"version", "name", "source"}})
    if kind == "css":
        rows = ["/* Generated by scripts/build_flow_visual_language.py; edit tokens.json. */", ":root {"]
        rows.extend(f"  --flow-vl-{css_name(key.replace('_', '-'))}: {value};" for key, value in values.items())
        rows.append("}")
        return "\n".join(rows) + "\n"
    if kind == "ts":
        payload = json.dumps(values, ensure_ascii=False, indent=2)
        return "/* Generated by scripts/build_flow_visual_language.py; edit tokens.json. */\nexport const VISUAL_TOKENS = " + payload + " as const;\n"
    rows = ["# Generated by scripts/build_flow_visual_language.py; edit tokens.json.", "VISUAL_TOKENS = {"]
    rows.extend(python_rows(values))
    rows.append("}")
    return "\n".join(rows) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if not isinstance(data.get("version"), str) or not data.get("colors") or not data.get("typography"):
        raise SystemExit("tokens.json 缺少 version、colors 或 typography")
    flattened = flatten({key: value for key, value in data.items() if key not in {"version", "name", "source"}})
    for key, value in flattened.items():
        if key.startswith("colors-") and not re.fullmatch(r"#[0-9A-Fa-f]{6}", value) and not value.startswith("rgba("):
            raise SystemExit(f"非法颜色 token: {key}={value}")
    drift = []
    for path, kind in OUTPUTS.items():
        content = generate(data, kind)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    css_path = next(path for path, kind in OUTPUTS.items() if kind == "css")
    css_content = generate(data, "css") if args.check else css_path.read_text(encoding="utf-8")
    specimen = ROOT / "packages/flow-visual-language/specimen.html"
    referenced_tokens = re.findall(r"var\((--flow-vl-[a-z0-9-]+)", specimen.read_text(encoding="utf-8"))
    missing_tokens = sorted(set(token for token in referenced_tokens if token not in css_content))
    if missing_tokens:
        raise SystemExit("specimen 引用未定义 token: " + ", ".join(missing_tokens))
    if drift:
        print("生成文件与 tokens.json 不一致: " + ", ".join(drift))
        return 1
    print("视觉语言令牌检查通过" if args.check else "视觉语言映射已生成")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
